import json
from datetime import datetime
from zoneinfo import ZoneInfo

from openai import AsyncOpenAI

from AI_SMM_AGENT.app.config.settings import settings


client = AsyncOpenAI(
    api_key=settings.PROXY_API_KEY,
    base_url="https://api.proxyapi.ru/openai/v1"
)


async def parse_schedule_time(user_text: str) -> dict:
    now_dt = datetime.now(ZoneInfo("Europe/Moscow"))
    now_str = now_dt.strftime("%Y-%m-%d %H:%M:%S")
    weekday_ru = ["понедельник", "вторник", "среда", "четверг", "пятница", "суббота", "воскресенье"][now_dt.weekday()]

    response = await client.chat.completions.create(
        model="gpt-4o-mini",
        temperature=0,
        response_format={"type": "json_object"},
        messages=[
            {
                "role": "system",
                "content": f"""Ты — точный парсер даты и времени на русском языке.

Текущий момент: {now_str} (Europe/Moscow)
Сегодня: {weekday_ru}

ПРАВИЛА ИНТЕРПРЕТАЦИИ ВРЕМЕНИ

Относительное время (от текущего момента):
- "через N минут/часов/дней" → прибавь к текущему времени
- "через час" → +1 час
- "через полчаса" → +30 минут
- "через сутки" → +24 часа

Время суток без даты:
- "в 15", "в 15:00", "в три часа дня" → ближайшее будущее с этим временем
- если указанное время уже прошло сегодня → завтра в это время

Дни недели:
- "в пятницу", "в четверг" → ближайший такой день в будущем (не сегодня, если сегодня этот день)
- "в пятницу следующей недели" → пятница следующей календарной недели
- "в пятницу этой недели" → пятница текущей календарной недели

Специальные слова:
- "сегодня" → текущая дата
- "завтра" → текущая дата + 1 день
- "послезавтра" → текущая дата + 2 дня
- "на следующей неделе" без дня → понедельник следующей недели

Сложные конструкции (разбирай пошагово):
- "без пяти шесть" → 05:55
- "без десяти три" → 02:50
- "в половину восьмого" → 07:30
- "в четверть второго" → 01:15
- "без четверти пять" → 04:45
- "на час и пять минут" → 01:05
- "в полдень" → 12:00
- "в полночь" → 00:00
- "утром" без времени → 09:00
- "днём" без времени → 14:00
- "вечером" без времени → 19:00
- "ночью" без времени → 23:00

Комбинации дня и времени:
- "завтра без пяти шесть" → завтра 05:55
- "в пятницу в половину восьмого" → ближайшая пятница 07:30
- "послезавтра вечером" → послезавтра 19:00
- "в следующий четверг на час и пять минут" → следующий четверг 01:05

Даты в явном виде:
- "01.06 в 14:30" → 2026-06-01 14:30:00 (если дата уже прошла — следующий год)
- "1 июня в 14:30" → аналогично

АЛГОРИТМ РАБОТЫ

1. Определи день (абсолютный или относительный)
2. Определи время (точное или приблизительное)
3. Если время задано словесно — переведи в цифры
4. Если что-то неоднозначно — задай один уточняющий вопрос
5. Верни JSON

ВЫВОД

Если время распознано:
{{"datetime": "YYYY-MM-DD HH:MM:00"}}

Если данных недостаточно или неоднозначно:
{{"datetime": null, "question": "короткий уточняющий вопрос"}}

Никакого текста вне JSON. Только один JSON-объект."""
            },
            {
                "role": "user",
                "content": user_text
            }
        ]
    )

    raw = response.choices[0].message.content
    return json.loads(raw)